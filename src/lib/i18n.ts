/** The message for a code the shop server sent. */
export function errorKey(code: string): CopyKey {
  const map: Record<string, CopyKey> = {
    busy: "errBusy",
    sold_out: "errSoldOut",
    unknown_item: "errSoldOut",
    rate_limited: "errLimited",
    too_large_order: "errTooLarge",
    card_unavailable: "errCardUnavailable",
    payment_unavailable: "errCardUnavailable",
    unreachable: "unreachable",
    not_configured: "notConfigured",
    allergens_unconfirmed: "needConfirm",
    not_found: "notFound",
  };
  return map[code] ?? "errGeneric";
}

export function useI18n() {
  const { locale } = useLocal();
  const dictionary = locale === "zh-Hant" ? zhHant : en;
  const t = (key: CopyKey) => dictionary[key];
  const setLocale = (next: Locale) => writeLocal({ locale: next });
  return { t, locale, setLocale };
}
